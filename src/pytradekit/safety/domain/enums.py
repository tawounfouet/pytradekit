"""Safety state, action, and reason taxonomies."""

from enum import StrEnum


class SafetyState(StrEnum):
    """Derived safety state of the governed runtime."""

    SAFE = "SAFE"
    DEGRADED = "DEGRADED"
    RESTRICTED = "RESTRICTED"
    HALTED = "HALTED"
    UNKNOWN = "UNKNOWN"


class SafetyAction(StrEnum):
    """Actions evaluated by the central SafetyGate."""

    VIEW = "VIEW"
    SUBMIT_RISK_INCREASING = "SUBMIT_RISK_INCREASING"
    SUBMIT_RISK_REDUCING = "SUBMIT_RISK_REDUCING"
    CANCEL_ORDER = "CANCEL_ORDER"
    PAUSE_STRATEGY = "PAUSE_STRATEGY"
    RESUME_STRATEGY = "RESUME_STRATEGY"
    RUN_RECONCILIATION = "RUN_RECONCILIATION"
    RESOLVE_MISMATCH = "RESOLVE_MISMATCH"
    ACTIVATE_KILL_SWITCH = "ACTIVATE_KILL_SWITCH"
    RELEASE_KILL_SWITCH = "RELEASE_KILL_SWITCH"
    CREATE_RISK_OVERRIDE = "CREATE_RISK_OVERRIDE"
    REVOKE_RISK_OVERRIDE = "REVOKE_RISK_OVERRIDE"


class SafetyReason(StrEnum):
    """Stable reason codes emitted by SafetyDecision."""

    ALLOWED = "ALLOWED"
    AUTHORIZATION_DENIED = "AUTHORIZATION_DENIED"
    EVIDENCE_UNAVAILABLE = "EVIDENCE_UNAVAILABLE"
    ECONOMIC_TRUTH_UNKNOWN = "ECONOMIC_TRUTH_UNKNOWN"
    ECONOMIC_TRUTH_INCONSISTENT = "ECONOMIC_TRUTH_INCONSISTENT"
    STATE_CONFIDENCE_LOW = "STATE_CONFIDENCE_LOW"
    RECOVERY_BLOCKED = "RECOVERY_BLOCKED"
    RECOVERY_IN_PROGRESS = "RECOVERY_IN_PROGRESS"
    RUNTIME_NOT_READY = "RUNTIME_NOT_READY"
    CRITICAL_HEALTH_UNHEALTHY = "CRITICAL_HEALTH_UNHEALTHY"
    RUNTIME_LIFECYCLE_RESTRICTED = "RUNTIME_LIFECYCLE_RESTRICTED"
    DEGRADED_OPERATION = "DEGRADED_OPERATION"
    RISK_POLICY_DENIED = "RISK_POLICY_DENIED"
    RISK_INCREASE_REQUIRES_SAFE_STATE = "RISK_INCREASE_REQUIRES_SAFE_STATE"
    RISK_REDUCTION_ALLOWED = "RISK_REDUCTION_ALLOWED"
    CANCEL_ALLOWED = "CANCEL_ALLOWED"
    RECONCILIATION_ALLOWED = "RECONCILIATION_ALLOWED"
    PAUSE_ALLOWED = "PAUSE_ALLOWED"
    RESUME_REQUIRES_SAFE_STATE = "RESUME_REQUIRES_SAFE_STATE"
    KILL_SWITCH_ACTIVE = "KILL_SWITCH_ACTIVE"
    RISK_OVERRIDE_APPLIED = "RISK_OVERRIDE_APPLIED"
    HARD_SAFETY_CANNOT_BE_OVERRIDDEN = "HARD_SAFETY_CANNOT_BE_OVERRIDDEN"
